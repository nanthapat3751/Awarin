import { useState, type KeyboardEvent } from "react";

/**
 * รู้ว่า Caps Lock เปิดอยู่ตอนกำลังพิมพ์ในช่องรหัสผ่าน
 *
 * ทำไมต้องมี: ช่องรหัสผ่านปิดตัวอักษรไว้ คนที่เผลอเปิด Caps Lock จะเห็นแค่จุดเหมือนเดิมทุกอย่าง
 * แล้วได้ข้อความว่า "อีเมลหรือรหัสผ่านไม่ถูกต้อง" ซึ่งชี้ไปผิดที่ · ระบบนี้ล็อกบัญชีชั่วคราวเมื่อ
 * พยายามผิดหลายครั้ง คนจึงโดนล็อกจากปุ่มเดียวที่ไม่มีอะไรบอกเลยว่ากดค้างอยู่
 *
 * ตรวจจาก getModifierState บนอีเวนต์แป้นพิมพ์ — เป็นวิธีเดียวที่เว็บทำได้ ผลคือ**ต้องพิมพ์ก่อน
 * อย่างน้อยหนึ่งปุ่มถึงจะรู้** (เบราว์เซอร์ไม่เปิดเผยสถานะปุ่มตอนแค่โฟกัส) ซึ่งยอมรับได้ เพราะ
 * จังหวะที่คำเตือนมีประโยชน์คือตอนกำลังพิมพ์รหัสอยู่พอดี
 *
 * ล้างค่าตอนออกจากช่อง ไม่งั้นคำเตือนจะค้างอยู่ทั้งที่ผู้ใช้กด Caps Lock ปิดไปแล้วนอกช่อง
 */
export function useCapsLock() {
  const [capsOn, setCapsOn] = useState(false);

  const track = (e: KeyboardEvent<HTMLInputElement>) => setCapsOn(e.getModifierState("CapsLock"));

  return {
    capsOn,
    /** กระจายลงช่องรหัสผ่านโดยตรง (ช่องอื่นไม่ต้องใช้ — ช่องที่อ่านตัวอักษรได้อยู่แล้วไม่มีปัญหานี้) */
    capsProps: {
      onKeyDown: track,
      onKeyUp: track,
      onBlur: () => setCapsOn(false),
    },
  };
}
