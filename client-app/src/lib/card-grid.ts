/**
 * เลือกจำนวนคอลัมน์ของตะแกรงการ์ดจาก "จำนวนรายการที่มีจริง" แทนการฟิกไว้ 3 คอลัมน์ตายตัว
 *
 * ปัญหาที่แก้ (วัดจากหน้าจริงตอน 1440px): หน้าแบบบ้านมี 2 แบบ แต่ตะแกรงเป็น 3 คอลัมน์ →
 * เหลือช่องว่างค้าง 1 ช่อง และการ์ดถูกบีบเหลือกว้าง 315px จากพื้นที่ 1024px ที่มี;
 * หน้าผลงานมี 4 รายการ → แถวที่สองมีใบเดียว เหลือรูโบ๋ 2 ช่อง
 *
 * กติกา: เลือกจำนวนคอลัมน์ที่ทำให้แถวสุดท้ายเต็มพอดี ถ้าเลี่ยงไม่ได้ก็ให้เหลือรูน้อยที่สุด
 *   1 รายการ  → 1 คอลัมน์ แต่คุมความกว้างไว้ ไม่ให้การ์ดใบเดียวยืดเต็มจอ
 *   2 รายการ  → 2 คอลัมน์ (เต็มพอดี)
 *   4 รายการ  → 2 คอลัมน์ (2×2 เต็มพอดี — ถ้าใช้ 3 จะเหลือรู 2 ช่อง)
 *   นอกนั้น   → 3 คอลัมน์ (3/6/9 เต็มพอดี; 5 กับ 7 เหลือรูน้อยกว่าการใช้ 2 คอลัมน์)
 *
 * ผลพลอยได้: พอรายการเพิ่มขึ้นเองในอนาคต ตะแกรงกลับไป 3 คอลัมน์โดยไม่ต้องมาแก้โค้ด
 * ใช้กับจำนวน "หลังกรองและแบ่งหน้าแล้ว" เสมอ ไม่ใช่จำนวนทั้งหมดในฐานข้อมูล
 */
export function cardGridClass(count: number): string {
  if (count <= 1) return "mx-auto max-w-lg grid-cols-1";
  if (count === 2 || count === 4) return "grid-cols-1 sm:grid-cols-2";
  return "grid-cols-1 sm:grid-cols-2 md:grid-cols-3";
}
