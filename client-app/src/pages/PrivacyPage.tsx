function SummaryCard({
  icon,
  title,
  children,
}: Readonly<{
  icon: ReactNode;
  title: string;
  children: ReactNode;
}>) {
  return (
    <div className="rounded-xl border border-slate-200 bg-white p-5">
      <div className="flex items-center gap-2.5">
        <span className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg bg-brand/8 text-brand">
          {icon}
        </span>
        <h3 className="text-base font-semibold text-slate-800">{title}</h3>
      </div>
      <div className="mt-3 space-y-1.5 text-sm leading-relaxed text-slate-600">{children}</div>
    </div>
  );
}

function Section({ id, title, children }: Readonly<{ id: string; title: string; children: ReactNode }>) {
  return (
    // scroll-mt กันหัวข้อถูกแถบเมนู fixed บังเมื่อกระโดดมาด้วย #anchor — ใช้ความสูงจริงจาก --nav-h
    <section id={id} className="scroll-mt-[calc(var(--nav-h)+1rem)]">
      <h2 className="text-lg font-semibold text-slate-800">{title}</h2>
      <div className="mt-3 space-y-3 leading-relaxed text-slate-600">{children}</div>
    </section>
  );
}

function Bullets({ items }: Readonly<{ items: ReactNode[] }>) {
  return (
    <ul className="ml-5 list-disc space-y-1.5 marker:text-slate-400">
      {items.map((item, i) => (
        <li key={i}>{item}</li>
      ))}
    </ul>
  );
}

