import { bahtText } from "../../src/lib/baht-text";

describe("bahtText", () => {
  it("อ่านยอดจริงจากสัญญาที่บริษัทใช้อยู่", () => {
    // ตัวเลขจากสัญญาบ้านคุณปวีณา แสงกล้า — ต้นฉบับเขียนไว้ว่า "(สองล้านหกแสนบาทถ้วน)"
    expect(bahtText(2_600_000)).toBe("สองล้านหกแสนบาทถ้วน");
    expect(bahtText(520_000)).toBe("ห้าแสนสองหมื่นบาทถ้วน");
    expect(bahtText(390_000)).toBe("สามแสนเก้าหมื่นบาทถ้วน");
    expect(bahtText(442_000)).toBe("สี่แสนสี่หมื่นสองพันบาทถ้วน");
    expect(bahtText(260_000)).toBe("สองแสนหกหมื่นบาทถ้วน");
    expect(bahtText(78_000)).toBe("เจ็ดหมื่นแปดพันบาทถ้วน");
  });

  it("หลักสิบใช้ 'สิบ' และ 'ยี่สิบ' ไม่ใช่ 'หนึ่งสิบ' / 'สองสิบ'", () => {
    expect(bahtText(10)).toBe("สิบบาทถ้วน");
    expect(bahtText(20)).toBe("ยี่สิบบาทถ้วน");
    expect(bahtText(25)).toBe("ยี่สิบห้าบาทถ้วน");
  });

  it("หลักหน่วยเป็น 1 อ่านว่า 'เอ็ด' เมื่อมีหลักอื่นนำหน้า", () => {
    expect(bahtText(1)).toBe("หนึ่งบาทถ้วน"); // เลขโดด ๆ ยังเป็น "หนึ่ง"
    expect(bahtText(11)).toBe("สิบเอ็ดบาทถ้วน");
    expect(bahtText(21)).toBe("ยี่สิบเอ็ดบาทถ้วน");
    expect(bahtText(101)).toBe("หนึ่งร้อยเอ็ดบาทถ้วน");
    expect(bahtText(1_000_001)).toBe("หนึ่งล้านหนึ่งบาทถ้วน");
  });

  it("ข้ามหลักที่เป็นศูนย์", () => {
    expect(bahtText(0)).toBe("ศูนย์บาทถ้วน");
    expect(bahtText(100)).toBe("หนึ่งร้อยบาทถ้วน");
    expect(bahtText(1_000_000)).toBe("หนึ่งล้านบาทถ้วน");
    expect(bahtText(10_000_000)).toBe("สิบล้านบาทถ้วน");
    expect(bahtText(11_000_000)).toBe("สิบเอ็ดล้านบาทถ้วน");
  });

  it("มีสตางค์ → ลงท้ายด้วยสตางค์ ไม่ใช่ 'ถ้วน'", () => {
    expect(bahtText(1059.3)).toBe("หนึ่งพันห้าสิบเก้าบาทสามสิบสตางค์");
    expect(bahtText(0.25)).toBe("ศูนย์บาทยี่สิบห้าสตางค์");
    expect(bahtText(1.01)).toBe("หนึ่งบาทหนึ่งสตางค์");
    expect(bahtText(1.21)).toBe("หนึ่งบาทยี่สิบเอ็ดสตางค์");
  });

  it("ปัดเป็นสตางค์ก่อนอ่าน ไม่ให้ทศนิยมลอยทำให้ได้ '...เก้าสิบเก้าสตางค์'", () => {
    expect(bahtText(0.1 + 0.2)).toBe("ศูนย์บาทสามสิบสตางค์");
    expect(bahtText(1177.005)).toBe("หนึ่งพันหนึ่งร้อยเจ็ดสิบเจ็ดบาทหนึ่งสตางค์");
  });

  it("ยอดติดลบมีคำว่า 'ลบ' นำหน้า และปฏิเสธค่าที่ไม่ใช่ตัวเลข", () => {
    expect(bahtText(-50)).toBe("ลบห้าสิบบาทถ้วน");
    expect(() => bahtText(Number.NaN)).toThrow();
    expect(() => bahtText(Number.POSITIVE_INFINITY)).toThrow();
  });
});
