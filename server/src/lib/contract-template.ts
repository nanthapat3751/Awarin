// จับทั้งก้อนใน {{ }} ด้วยตัวอ่านกลาง (scanVariableTokens ใน shared-types — หน้าจอพนักงานใช้ตัวเดียวกัน)
// แล้วค่อยตัดช่องว่างหัวท้ายในโค้ด (variableName)

/** ชื่อตัวแปรใน {{ ... }} · ข้างในเป็นช่องว่างล้วน = คงไว้ตามเดิม (นับเป็นตัวแปรที่ไม่รู้จัก) */
function variableName(inner: string): string {
  return inner.trim() || inner;
}

/**
 * โทเคนที่ "ไม่ใช่" ข้อความ แต่เป็นบล็อกที่ตัวพิมพ์เอกสารวาดให้ตอนออก PDF
 *
 * ต่างจากตัวแปรทั่วไปตรงที่ไม่ถูกแทนค่าตอนแช่แข็ง — มันค้างอยู่ในเนื้อสัญญาแล้วถูกแทนที่ด้วย
 * ตารางงวดเงินของสัญญาฉบับนั้นตอนพิมพ์ ทำแบบนี้ได้เพราะงวดเงินเป็นข้อมูลของ "สัญญาฉบับนั้น"
 * (ล็อกพร้อมกันตอนลงนาม) ไม่ใช่ข้อมูลของแม่แบบที่แก้ทีหลังได้
 */
export const CONTRACT_BLOCK_TOKENS = ["ตารางงวดงาน"] as const;

/** โทเคนตารางงวดงานแบบเต็มรูป — ตัวพิมพ์ PDF ตัดข้อความด้วยสตริงนี้ ห้ามพิมพ์ซ้ำที่อื่น */
export const INSTALLMENT_TABLE_TOKEN = "{{ตารางงวดงาน}}";

/**
 * เนื้อสัญญาก้อนนี้จะพิมพ์ตารางงวดเงินออกมาไหม
 *
 * ถ้าไม่มีโทเคน งวดที่กรอกไว้จะถูกบันทึกแต่ไม่โผล่บนกระดาษเลยโดยไม่มีอะไรเตือน —
 * เป็นความผิดพลาดระดับหลักแสนที่เงียบที่สุดเท่าที่ฟีเจอร์นี้ทำให้เกิดได้ จึงต้องตรวจได้จากที่เดียวกัน
 */
export function bodyPrintsInstallments(structure: ContractStructure): boolean {
  return structure.clauses.some((c) => c.body.includes(INSTALLMENT_TABLE_TOKEN));
}

/**
 * แทนค่าตัวแปรในข้อความหนึ่งก้อน
 *
 * ตัวแปรที่สะกดผิดหรือไม่มีในรายการจะถูกปล่อยไว้เหมือนเดิม ไม่ใช่ลบทิ้งหรือใส่ค่าว่าง —
 * เพราะข้อความ "{{ชื่อผู้วาจ้าง}}" ที่โผล่บนสัญญาจริงคือสัญญาณให้คนเห็นแล้วรู้ว่าพิมพ์ผิด
 * ส่วนช่องว่างเปล่า ๆ จะเนียนจนหลุดไปถึงลูกค้า
 */
export function fillVariables(text: string, vars: ContractVariables): string {
  return replaceVariableTokens(text, (whole, inner) => {
    const value = (vars as unknown as Record<string, string>)[variableName(inner)];
    return value ?? whole;
  });
}

/** ชื่อตัวแปรที่พิมพ์ผิด/ไม่รู้จักในแม่แบบ — ใช้เตือนตอนบันทึกแม่แบบ ไม่ใช่บล็อก */
export function unknownVariables(structure: ContractStructure): string[] {
  const texts = [
    structure.coverSubtitle,
    structure.preamble,
    structure.closing,
    ...structure.clauses.flatMap((c) => [c.heading, c.body]),
  ];
  const known = new Set<string>([...CONTRACT_VARIABLE_NAMES, ...CONTRACT_BLOCK_TOKENS]);
  const found = new Set<string>();
  for (const t of texts) {
    for (const token of scanVariableTokens(t)) {
      const name = variableName(token.inner);
      if (!known.has(name)) found.add(name);
    }
  }
  return [...found];
}

/** แทนค่าตัวแปรทั้งแม่แบบ → เนื้อสัญญาที่พร้อมแช่แข็งลงฉบับนั้น */
export function renderStructure(
  structure: ContractStructure,
  vars: ContractVariables,
): ContractStructure {
  return {
    coverSubtitle: fillVariables(structure.coverSubtitle, vars),
    preamble: fillVariables(structure.preamble, vars),
    closing: fillVariables(structure.closing, vars),
    clauses: structure.clauses.map((c) => ({
      heading: fillVariables(c.heading, vars),
      body: fillVariables(c.body, vars),
    })),
  };
}

const THAI_MONTHS = [
  "มกราคม", "กุมภาพันธ์", "มีนาคม", "เมษายน", "พฤษภาคม", "มิถุนายน",
  "กรกฎาคม", "สิงหาคม", "กันยายน", "ตุลาคม", "พฤศจิกายน", "ธันวาคม",
];

/** "1 พฤษภาคม 2565" — สัญญาไทยใช้ปี พ.ศ. เต็ม ไม่ใช่ 1/5/2022 */
export function thaiLongDate(d: Date): string {
  return `${d.getDate()} ${THAI_MONTHS[d.getMonth()]} ${d.getFullYear() + 543}`;
}

export function contractMoney(n: number): string {
  return n.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

